"""Timetable export service for CSV and Excel (.xlsx) formats.

Implements TRD Section L.4, L.5, PRD FR-022, DD-031, and DD-037:
- Exports canonical current_timetable to CSV and multi-sheet Excel (.xlsx).
- Guards against exporting invalid timetables unless explicitly overridden (DD-031).
- Protects against spreadsheet formula injection (DD-037).
"""

from __future__ import annotations

import io
from typing import Any, Dict, List

import pandas as pd

from src.csp.models import Dataset, ScheduledSession, Timetable

DAYS_OF_WEEK = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


class ExportError(Exception):
    """Raised when timetable export cannot proceed."""

    pass


def _sanitize_cell(val: Any) -> str:
    """Sanitize spreadsheet cell against formula injection (DD-037).

    Prefixes characters '=', '+', '-', '@' with a single quote.
    """
    s = str(val) if val is not None else ""
    if s and s[0] in ("=", "+", "-", "@"):
        return f"'{s}"
    return s


def build_export_dataframe(timetable: Timetable, dataset: Dataset) -> pd.DataFrame:
    """Build standardized tabular representation of the timetable (TRD F.2.11)."""
    rows = []
    # Sort sessions by day, start_period, class_id
    sorted_sessions = sorted(
        timetable.scheduled_sessions,
        key=lambda s: (s.day, s.start_period, s.class_id),
    )

    for s in sorted_sessions:
        day_str = DAYS_OF_WEEK[s.day] if 0 <= s.day < len(DAYS_OF_WEEK) else f"Day {s.day}"
        period_str = f"P{s.start_period}" if s.duration_periods == 1 else f"P{s.start_period}-P{s.start_period + s.duration_periods - 1}"

        cls_obj = dataset.get_class(s.class_id)
        class_name = cls_obj.name if cls_obj else s.class_id

        subj_obj = dataset.get_subject(s.subject_id)
        subject_name = subj_obj.name if subj_obj else s.subject_id

        teacher_obj = dataset.get_teacher(s.teacher_id)
        teacher_name = teacher_obj.name if teacher_obj else s.teacher_id

        rows.append({
            "Day": _sanitize_cell(day_str),
            "Period": _sanitize_cell(period_str),
            "Class ID": _sanitize_cell(s.class_id),
            "Class Name": _sanitize_cell(class_name),
            "Subject ID": _sanitize_cell(s.subject_id),
            "Subject Name": _sanitize_cell(subject_name),
            "Teacher ID": _sanitize_cell(s.teacher_id),
            "Teacher Name": _sanitize_cell(teacher_name),
            "Room ID": _sanitize_cell(s.room_id),
            "Duration": s.duration_periods,
            "Requirement ID": _sanitize_cell(s.requirement_id),
        })

    return pd.DataFrame(rows)


def to_csv(
    timetable: Timetable,
    dataset: Dataset,
    allow_invalid_export: bool = False,
) -> str:
    """Serialize the schedule to a CSV string (TRD L.4 & DD-031)."""
    if timetable.status != "Valid" and not allow_invalid_export:
        raise ExportError(
            f"Cannot export timetable with status '{timetable.status}'. "
            "Timetable has hard violations. Set allow_invalid_export=True to force export."
        )

    df = build_export_dataframe(timetable, dataset)
    return df.to_csv(index=False)


def to_excel(
    timetable: Timetable,
    dataset: Dataset,
    allow_invalid_export: bool = False,
) -> bytes:
    """Serialize the schedule to Excel (.xlsx) bytes with multiple inspection sheets."""
    if timetable.status != "Valid" and not allow_invalid_export:
        raise ExportError(
            f"Cannot export timetable with status '{timetable.status}'. "
            "Timetable has hard violations. Set allow_invalid_export=True to force export."
        )

    df_master = build_export_dataframe(timetable, dataset)

    output = io.BytesIO()
    with pd.ExcelWriter(output, engine="openpyxl") as writer:
        # Sheet 1: Master Log
        df_master.to_excel(writer, sheet_name="Master Timetable", index=False)

        # Sheet 2: Metadata & Summary
        summary_rows = [
            {"Property": "Dataset ID", "Value": dataset.dataset_id},
            {"Property": "Total Scheduled Sessions", "Value": len(timetable.scheduled_sessions)},
            {"Property": "Total Unscheduled Sessions", "Value": len(timetable.unscheduled_requirement_ids)},
            {"Property": "Validation Status", "Value": timetable.status},
            {"Property": "Generated By", "Value": timetable.generated_by},
            {"Property": "Generated At", "Value": str(timetable.generated_at)},
        ]
        pd.DataFrame(summary_rows).to_excel(writer, sheet_name="Summary", index=False)

    return output.getvalue()
